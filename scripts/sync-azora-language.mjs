import { promises as fs } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const websiteRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const languageRoot = path.resolve(
  process.env.AZORA_LANG_ROOT || path.join(websiteRoot, '..', 'azora-lang'),
)
const version = process.argv[2] || '0.0.5'

async function collectAzoraFiles(directory) {
  const entries = await fs.readdir(directory, { withFileTypes: true })
  const files = []
  for (const entry of entries) {
    const absolute = path.join(directory, entry.name)
    if (entry.isDirectory()) files.push(...await collectAzoraFiles(absolute))
    else if (entry.isFile() && entry.name.endsWith('.az')) files.push(absolute)
  }
  return files
}

function quotedValues(source) {
  return [...source.matchAll(/"([A-Za-z_][A-Za-z0-9_]*)"/g)].map((match) => match[1])
}

async function writeVocabulary() {
  const vocabularyPath = path.join(
    languageRoot,
    'compiler/src/commonMain/kotlin/org/azora/lang/frontend/AzoraSyntaxVocabulary.kt',
  )
  const source = await fs.readFile(vocabularyPath, 'utf8')
  const reservedBlock = source.match(/reservedKeywords:[\s\S]*?= mapOf\(([\s\S]*?)\n\s*\)/)?.[1]
  const contextualBlock = source.match(/contextualKeywords:[\s\S]*?= setOf\(([^)]*)\)/)?.[1]
  if (!reservedBlock || !contextualBlock) {
    throw new Error(`Could not parse compiler vocabulary at ${vocabularyPath}`)
  }

  const reserved = [...reservedBlock.matchAll(/"([A-Za-z_][A-Za-z0-9_]*)"\s+to\s+TokenType\./g)]
    .map((match) => match[1])
    .sort()
  const contextual = quotedValues(contextualBlock).sort()
  const lines = [
    '/** Generated by scripts/sync-azora-language.mjs. Do not edit manually. */',
    `export const AZORA_RESERVED_KEYWORDS = Object.freeze(${JSON.stringify(reserved, null, 2)})`,
    '',
    `export const AZORA_CONTEXTUAL_KEYWORDS = Object.freeze(${JSON.stringify(contextual, null, 2)})`,
    '',
    'const escaped = AZORA_RESERVED_KEYWORDS.map((keyword) =>',
    "  keyword.replace(/[.*+?^${}()|[\\]\\\\]/g, '\\\\$&'))",
    '',
    'export const AZORA_KEYWORD_PATTERN = new RegExp(`\\\\b(?:${escaped.join(\'|\')})\\\\b`)',
    '',
  ]
  await fs.writeFile(
    path.join(websiteRoot, 'src/data/azora-vocabulary.js'),
    lines.join('\n'),
  )
}

async function writeWorkspace() {
  const stdRoot = path.join(languageRoot, 'std')
  const files = (await collectAzoraFiles(stdRoot)).sort()
  const documents = await Promise.all(files.map(async (absolute) => {
    const relative = path.relative(languageRoot, absolute).split(path.sep).join('/')
    return {
      uri: `azora-stdlib:///${relative}`,
      path: relative,
      source: await fs.readFile(absolute, 'utf8'),
    }
  }))
  const outputDirectory = path.join(websiteRoot, 'public/azls', version)
  await fs.mkdir(outputDirectory, { recursive: true })
  await fs.writeFile(
    path.join(outputDirectory, 'stdlib.json'),
    `${JSON.stringify({ version, documents })}\n`,
  )
}

await Promise.all([writeVocabulary(), writeWorkspace()])
console.log(`Synced Azora ${version}: compiler vocabulary and ${languageRoot}/std`)
